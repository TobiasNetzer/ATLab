# Writes manifest.nsh with the list of published files, called by ATLab_Setup.nsi while compiling.
# The installer stores the list as install.manifest in the program folder, so uninstalling and updating delete exactly
# these files and keep files the user added (e.g. a J-Link or FTDI DLL copied into the ATLab folder).
param(
    [Parameter(Mandatory)] [string] $Source,
    [Parameter(Mandatory)] [string] $Output
)

$ErrorActionPreference = 'Stop'

$root = (Resolve-Path -LiteralPath $Source).Path.TrimEnd('\')

function Relative([string] $path) { $path.Substring($root.Length + 1) }

# NSIS treats $ as variable prefix
function Escape([string] $path) { $path.Replace('$', '$$') }

$files = Get-ChildItem -LiteralPath $root -Recurse -File | ForEach-Object { Relative $_.FullName } | Sort-Object

# Deepest folders first, so they are empty when the parent folder is removed
$folders = Get-ChildItem -LiteralPath $root -Recurse -Directory |
    ForEach-Object { Relative $_.FullName } |
    Sort-Object -Property @{ Expression = { ($_ -split '\\').Count }; Descending = $true }, @{ Expression = { $_ } }

$lines = @(
    '; Generated by gen-manifest.ps1 from the published files, do not edit.'
    '!macro WRITE_MANIFEST'
)
$lines += $files | ForEach-Object { '  FileWrite $9 "F|' + (Escape $_) + '$\r$\n"' }
$lines += $folders | ForEach-Object { '  FileWrite $9 "D|' + (Escape $_) + '$\r$\n"' }
$lines += '!macroend'

Set-Content -LiteralPath $Output -Value $lines -Encoding ASCII
Write-Host "manifest.nsh: $($files.Count) files, $($folders.Count) folders"
